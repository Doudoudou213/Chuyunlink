'use strict';
const assert = require('node:assert/strict');
const model = require('../static/exploration-journey-state');
let checks = 0;
function check(value, name) { assert(value,name); checks++; }
const now = 1000000000;
let state = model.create('first',now);
check(state.phase === 'active' && !state.observed.length,'start is not an observation');
state = model.transition(state,'select','baiyun',now);
check(state.index === 2 && !state.observed.length,'selecting does not award or count arrival');
state = model.transition(state,'observe',null,now);
check(state.observed.join() === 'baiyun' && state.index === 3,'explicit observation advances once');
state = model.transition(state,'previous',null,now);
state = model.transition(state,'observe',null,now);
check(state.observed.length === 1,'revisiting does not duplicate observation');
state = model.transition(state,'pause',null,now);
check(model.transition(state,'observe',null,now).observed.length === 1,'pause blocks observation');
check(model.transition(state,'select','tower',now).index === 3,'pause blocks navigation');
state = model.transition(state,'resume',null,now);
state = model.transition(state,'observe',null,now);
check(state.phase === 'finished' && state.observed.length === 2,'early skipped stops remain unrecorded');
check(model.transition(state,'observe',null,now).observed.length === 2,'finished state blocks double record');
state = model.transition(state,'note','记'.repeat(150),now);
check(state.note.length === 120,'bounded local note');
check(model.restore({...state,phase:'active'},now).phase === 'paused','reload never auto resumes');
check(!model.restore({...state,updatedAt:now-8*86400000},now),'expired local record not restored');
check(!model.restore({...state,updatedAt:now+120000},now),'future invalid record ignored');
for (const change of [{route:'__proto__'},{index:20},{index:-1},{version:999},{phase:'arrived'}]) check(!model.restore({...state,...change},now),'invalid data rejected '+JSON.stringify(change));
check(model.restore({...state,observed:['tower','tower','unknown']},now).observed.join() === 'tower','saved ids restricted and deduplicated');
check(model.restore({...state,note:{html:'bad'}},now).note === '','malformed note ignored');
check(model.create('garden',now).route === 'garden' && model.routes.garden.stops.length === 3,'alternative reading sequence supported');
console.log('PASS journey state: '+checks+' checks. No navigation, reward or backend writes.');

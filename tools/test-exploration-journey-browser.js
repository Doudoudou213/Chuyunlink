'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { start } = require('./lib/exploration-motion-demo-preview');
const output = path.resolve(__dirname,'../artifacts/exploration-journey');
(async () => {
  const server = await start(); let browser, checks = 0;
  const errors = [], remote = [];
  const check = (value,name) => { assert(value,name); checks++; };
  async function open(width, options = {}) {
    const page = await browser.newPage({viewport:{width,height:900},...options});
    page.on('pageerror',error => errors.push(error.message));
    await page.route('**/*',route => {
      if (!route.request().url().startsWith(server.url)) { remote.push(route.request().url()); return route.abort(); }
      return route.continue();
    });
    return page;
  }
  const url = server.url+'/explore-journey-demo.html';
  const phase = page => page.locator('.journey-shell').getAttribute('data-phase');
  try {
    browser = await chromium.launch({channel:'msedge',headless:true}); fs.mkdirSync(output,{recursive:true});
    for (const width of [320,390,768,1440]) {
      const page = await open(width,{reducedMotion:'reduce'});
      await page.goto(url);
      check(await phase(page) === 'welcome','welcome '+width);
      await page.screenshot({path:path.join(output,'welcome-'+width+'.png'),fullPage:true});
      await page.locator('#journey-start').click();
      check(await phase(page) === 'active','start '+width);
      await page.waitForFunction(() => document.querySelector('#journey-light').dataset.profile === 'tower');
      check(await page.locator('#journey-light').getAttribute('data-render-mode') === 'light-only','reused original-painting illumination '+width);
      check(await page.locator('#journey-light').getAttribute('data-phase') === 'settled','reduced motion respected '+width);
      await page.locator('#reading-details summary').click();
      check(await page.locator('#journey-story').isVisible(),'reading disclosure '+width);
      await page.screenshot({path:path.join(output,'active-'+width+'.png'),fullPage:true});
      await page.locator('#journey-observe').click();
      check(await page.locator('#journey-title').textContent() === '古铜顶','next place '+width);
      await page.locator('#journey-pause').click();
      check(await phase(page) === 'paused' && await page.locator('#journey-light').isHidden(),'pause stops light '+width);
      await page.reload();
      check(await phase(page) === 'paused' && (await page.locator('#paused-copy').textContent()).includes('古铜顶'),'restore exact stop '+width);
      await page.locator('#journey-resume').click();
      for (let i=0;i<3;i++) await page.locator('#journey-observe').click();
      check(await phase(page) === 'finished','complete sequence '+width);
      check(await page.locator('#souvenir-stops li').count() === 4,'honest four observations '+width);
      const note = '<img src=x onerror=alert(1)> 喜欢层檐';
      await page.locator('#journey-note').fill(note);
      check(await page.locator('#souvenir-note').textContent() === note && await page.locator('#souvenir-note img').count() === 0,'note is text, not HTML '+width);
      await page.locator('#journey-note').fill('沿着金线，看见层层屋檐。');
      const downloadPromise = page.waitForEvent('download'); await page.locator('#journey-save').click();
      const download = await downloadPromise;
      check(fs.readFileSync(await download.path(),'utf8').includes('非实地到访'),'download carries honest boundary '+width);
      await page.screenshot({path:path.join(output,'finished-'+width+'.png'),fullPage:true});
      await page.reload();
      check(await phase(page) === 'finished' && (await page.locator('#journey-note').inputValue()).includes('金线'),'finished note restores '+width);
      await page.emulateMedia({media:'print'});
      check(await page.locator('.painting').isHidden() && await page.locator('.souvenir').isVisible() && await page.locator('#journey-note').isHidden(),'print contains souvenir without controls '+width);
      if (width === 1440) await page.pdf({path:path.join(output,'souvenir-print.pdf'),format:'A4',printBackground:true});
      await page.emulateMedia({media:'screen'});
      check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),'no page overflow '+width);
      check(await page.locator('button').evaluateAll(nodes => nodes.every(node => { const b=node.getBoundingClientRect(); return !b.width || b.width>=44 && b.height>=44; })),'44px buttons '+width);
      await page.locator('#journey-review').click();
      check(await phase(page) === 'active','continue reading '+width);
      page.once('dialog',dialog => dialog.dismiss()); await page.locator('#journey-reset').click();
      check(await phase(page) === 'active','cancel preserves data '+width);
      page.once('dialog',dialog => dialog.accept()); await page.locator('#journey-reset').click();
      check(await phase(page) === 'welcome','explicit clear '+width);
      await page.locator('[value=garden]').check(); await page.locator('#journey-start').click();
      check(await page.locator('#journey-title').textContent() === '鹅池','garden opens at pond '+width);
      await page.locator('#journey-finish').click();
      check(await page.locator('#souvenir-stops li').count() === 0,'early close invents no completion '+width);
      await page.close();
    }
    const live = await open(390); await live.goto(url); await live.locator('#journey-start').click();
    await live.waitForFunction(() => document.querySelector('#journey-light').dataset.profile === 'tower');
    await live.evaluate(() => ['pond','copper','baiyun'].forEach(id => document.querySelector('[data-stop="'+id+'"]').click()));
    await live.waitForFunction(() => document.querySelector('#journey-light').dataset.profile === 'baiyun');
    check(await live.locator('#journey-title').textContent() === '白云阁','rapid selection retains matching text and light');
    await live.waitForTimeout(400);
    const stageBox = await live.locator('#journey-stage').boundingBox();
    await live.locator('#journey-stage').evaluate(node => { node.scrollLeft = 0; });
    await live.mouse.move(stageBox.x+stageBox.width*.7,stageBox.y+stageBox.height*.7);
    await live.mouse.down(); await live.mouse.move(stageBox.x+stageBox.width*.25,stageBox.y+stageBox.height*.7,{steps:10}); await live.mouse.up();
    check(await live.locator('#journey-stage').evaluate(node => node.scrollLeft > 50),'mouse drag explores painting');
    check(await live.locator('#journey-title').textContent() === '白云阁','drag does not falsely choose a point');
    await live.keyboard.press('Tab'); await live.locator('#journey-stage').focus();
    const scrollBefore = await live.locator('#journey-stage').evaluate(node => node.scrollLeft);
    await live.keyboard.press('ArrowRight');
    check(await live.locator('#journey-stage').evaluate(node => node.scrollLeft) > scrollBefore,'keyboard scroll works');
    check(await live.locator('#journey-stage').evaluate(node => node.matches(':focus-visible')),'map keyboard focus visible');
    await live.evaluate(() => { Object.defineProperty(document,'hidden',{configurable:true,value:true}); document.dispatchEvent(new Event('visibilitychange')); });
    const progress = await live.locator('#journey-light').getAttribute('data-progress');
    await live.waitForTimeout(160);
    check(await live.locator('#journey-light').getAttribute('data-progress') === progress,'background freezes playback');
    await live.close();
    const denied = await open(390);
    await denied.addInitScript(() => Object.defineProperty(window,'localStorage',{get(){throw new Error('disabled');}}));
    await denied.route('**/hhl-full-park-v2.webp',route => route.abort());
    await denied.route('**/gsap-3.15.0.min.js',route => route.abort());
    await denied.goto(url); await denied.locator('#journey-start').click();
    check(await denied.locator('#art-error').isVisible(),'missing image explicitly disclosed');
    check((await denied.locator('#journey-status').textContent()).includes('不允许保存'),'storage failure disclosed');
    await denied.locator('#journey-observe').click();
    check(await denied.locator('#journey-title').textContent() === '古铜顶','reading usable without art, storage or GSAP');
    await denied.close();
    const corrupt = await open(390);
    await corrupt.addInitScript(() => localStorage.setItem('chulink:journey-demo:v1','{bad json'));
    await corrupt.goto(url);
    check(await phase(corrupt) === 'welcome' && (await corrupt.locator('#journey-status').textContent()).includes('无法读取'),'malformed record recoverable');
    await corrupt.locator('#journey-start').click(); await corrupt.locator('#journey-observe').click();
    check(await corrupt.evaluate(() => JSON.parse(localStorage.getItem('chulink:journey-demo:v1')).index) === 1,'valid new record replaces malformed state only after starting');
    await corrupt.close();
    check(!errors.length,'no browser errors: '+errors.join(';'));
    check(!remote.length,'local assets only, no cloud writes');
    console.log('PASS journey browser: '+checks+' checks; 4 viewport welcome / reading / souvenir captures.');
  } finally { if(browser) await browser.close(); await server.close(); }
})().catch(error => {console.error(error); process.exitCode=1;});
